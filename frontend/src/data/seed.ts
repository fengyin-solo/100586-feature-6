import type { EntryRow, FieldHistory, HandoverRecord } from './types'

// 示例数据：首次打开时播种，之后浏览器里的改动优先，重置才会回到这份。
// 泵站行自带：管护班组、版本号（乐观锁）、字段定档台账、责任移交链。

function baseline(field: string, value: string, team: string, operator: string, at = '2026-06-01 09:00'): FieldHistory {
  return { field, value, team, operator, at }
}

type StationSeed = {
  id: number
  status: string
  站名: string
  所属片区: string
  管护班组: string
  设计流量: string
  装机台数: string
  服务面积: string
  投运日期: string
  站长: string
  站点状态: string
  /** 字段定档台账的初始责任班组，默认与当前管护班组一致；移交过来的站按字段注明原班组 */
  档?: Partial<Record<string, { team: string; operator: string; at: string }>>
  handovers?: HandoverRecord[]
}

function stationRow(seed: StationSeed): EntryRow {
  const values: Record<string, string> = {
    站名: seed.站名,
    所属片区: seed.所属片区,
    管护班组: seed.管护班组,
    设计流量: seed.设计流量,
    装机台数: seed.装机台数,
    服务面积: seed.服务面积,
    投运日期: seed.投运日期,
    站长: seed.站长,
    站点状态: seed.站点状态,
  }
  const history: FieldHistory[] = Object.entries(values).map(([field, value]) => {
    const kept = seed.档?.[field]
    return baseline(
      field,
      value,
      kept?.team ?? seed.管护班组,
      kept?.operator ?? seed.站长,
      kept?.at ?? '2026-06-01 09:00',
    )
  })
  const handovers: HandoverRecord[] = seed.handovers ?? [
    {
      seq: 0,
      kind: '派班',
      at: '2026-06-01 09:00',
      operator: '王调度',
      fromTeam: '',
      toTeam: seed.管护班组,
      fromDistrict: '',
      toDistrict: seed.所属片区,
      reason: '建成投运，首次派定管护班组',
    },
  ]
  return {
    id: seed.id,
    status: seed.status,
    pending: seed.status !== '已停用',
    abnormal: false,
    版本: 1,
    ...values,
    字段定档: history,
    移交记录: handovers,
  }
}

// 未派班组的站：字段定档台账挂在调度台名下，派班后才进正常档案。
function unassignedRow(seed: {
  id: number
  status: string
  站名: string
  所属片区: string
  设计流量: string
  装机台数: string
  服务面积: string
  投运日期: string
  站长: string
  站点状态: string
}): EntryRow {
  return stationRow({ ...seed, 管护班组: '尚未派班组' })
}

